
<?php

// Simple Function
function greet() {
    echo "Welcome to PHP Programming!<br>";
}

// Calling Simple Function
greet();


// Parameterized Function
function addition($a, $b) {
    $sum = $a + $b;
    echo "Addition of $a and $b is: $sum<br>";
}

// Calling Parameterized Function
addition(10, 20);
addition(50, 30);

?>
